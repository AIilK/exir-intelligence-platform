def visible_pages(allowed: set[str] | None = None) -> dict[str, dict[str, str]]:
    return {k: p for k, p in PAGES.items() if allowed is None or k in allowed}


def page_guide_text(allowed: set[str] | None = None) -> str:
    lines = [f"- {key}: «{p['title']}» — {p['what']}" for key, p in visible_pages(allowed).items()]
    return "\n".join(lines)


